"""The CardContact key-blob reference against the committed vectors.

`firmware/tests/vectors/cardcontact_wrap.txt` was generated by this
reference; `picohsm_wrap.txt` by pico-hsm's C `dkek_encode_key`.  Both must
decode here, and the reference must re-create its own blobs exactly.
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
VECTORS = ROOT / "firmware" / "tests" / "vectors"

_spec = importlib.util.spec_from_file_location(
    "cardcontact_wrap", ROOT / "tools" / "python" / "pico2hsm" / "cardcontact_wrap.py"
)
cc = importlib.util.module_from_spec(_spec)
sys.modules["cardcontact_wrap"] = cc
_spec.loader.exec_module(cc)


def _parse(path):
    glob, cases, cur = {}, [], None
    for line in path.read_text().splitlines():
        line = line.rstrip()
        if not line or line.startswith("#"):
            continue
        k, _, v = line.partition(" ")
        if k == "case":
            cur = {"name": v}
        elif k == "end":
            cases.append(cur)
            cur = None
        elif cur is not None:
            cur[k] = v.strip()
        else:
            glob[k] = v.strip()
    return glob, cases


def test_curve_parameters():
    cc.check_curves()


def test_kcv_and_share_combination():
    g, _ = _parse(VECTORS / "cardcontact_wrap.txt")
    dkek = cc.combine_shares(bytes.fromhex(g["share1"]), bytes.fromhex(g["share2"]))
    assert dkek.hex() == g["dkek"]
    assert cc.kcv(dkek).hex() == g["kcv"]


def test_vectors_decode():
    for name in ("cardcontact_wrap.txt", "picohsm_wrap.txt"):
        g, cases = _parse(VECTORS / name)
        dkek = bytes.fromhex(g["dkek"])
        assert cases
        for c in cases:
            u = cc.unwrap(dkek, bytes.fromhex(c["blob"]))
            assert u.policy.algorithms.hex() == c["algorithms"], c["name"]
            if c["kind"] == "ec":
                assert int.from_bytes(u.fields[5], "big") == int(c["d"], 16), c["name"]
                assert u.fields[6].hex() == c["q"], c["name"]
            elif c["kind"] == "aes":
                assert u.fields[0].hex() == c["key"], c["name"]
            else:
                n = u.fields[1] if c["kind"] == "rsa" else u.fields[5]
                assert int.from_bytes(n, "big") == int(c["n"], 16), c["name"]


def test_ec_blobs_are_reproducible():
    g, cases = _parse(VECTORS / "cardcontact_wrap.txt")
    dkek = bytes.fromhex(g["dkek"])
    for c in cases:
        if c["kind"] != "ec" or c["exact"] != "1":
            continue
        curve = cc.CURVES[c["curve"]]
        size, mat = cc.ec_material(curve, int(c["d"], 16))
        pol = cc.Policy(bytes.fromhex(c["algorithms"]), bytes.fromhex(c["access"]))
        blob = cc.wrap(dkek, cc.KEY_TYPE_EC, cc.OID_ECDSA_SHA256, size, mat,
                       bytes.fromhex(c["randomize"]), pol)
        assert blob.hex() == c["blob"], c["name"]
