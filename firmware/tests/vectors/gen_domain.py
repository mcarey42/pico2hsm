#!/usr/bin/env python3
"""Generate the domain known-answer vectors (cluster plan V3, phase P1).

Writes `domain_v1.txt` next to this script, using the independent Python
reference `tools/python/pico2hsm/domain.py` (not the firmware).  Read by
`firmware/tests/domain_vectors.rs` and by `pico2hsm-tool`'s
`pico2hsm-proto` crate.  Everything is deterministic (ECDSA per RFC 6979),
so re-running reproduces the file byte for byte.  Needs `cryptography`
>= 42 built against OpenSSL >= 3.2 for deterministic signing:

    python3 firmware/tests/vectors/gen_domain.py
"""

from __future__ import annotations

import hashlib
import importlib.util
import pathlib
import sys

from cryptography.hazmat.primitives.asymmetric import ec

HERE = pathlib.Path(__file__).resolve().parent
REF = HERE.parents[2] / "tools" / "python" / "pico2hsm" / "domain.py"

# Load the module file directly: the package __init__ pulls in pyscard.
_spec = importlib.util.spec_from_file_location("domain", REF)
dom = importlib.util.module_from_spec(_spec)
sys.modules["domain"] = dom
_spec.loader.exec_module(dom)


def h(b: bytes) -> str:
    return b.hex()


def member_key(label: str) -> tuple[int, bytes]:
    d = int.from_bytes(hashlib.sha256(b"pico2hsm KAT member " + label.encode()).digest(),
                       "big") % (dom.P256_N - 1) + 1
    pub = dom.point_bytes(ec.derive_private_key(d, ec.SECP256R1()).public_key())
    return d, pub


# The DKEK shares of the CardContact vectors (gen_cardcontact_wrap.py).
SHARE1 = hashlib.sha256(b"pico2hsm KAT DKEK share 1").digest()
SHARE2 = hashlib.sha256(b"pico2hsm KAT DKEK share 2").digest()


def main() -> None:
    out = [
        "# pico2hsm domain vectors (cluster plan V3 §4.1, §4.3), format v1.",
        "# Generated by gen_domain.py from the independent Python reference",
        "# tools/python/pico2hsm/domain.py.  Do not edit.",
        "#",
        "# Each case: dkek (or shares, XORed into dkek), kcv, okm (48-byte",
        "# HKDF output), d (domain scalar), q (Q_domain), domain_id, then one",
        "# member certificate: member_d, member_pub, member_id, sponsor_id,",
        "# lamport, flags, cert (187 bytes, ECDSA RFC 6979, exact).",
        "",
    ]

    def case(name: str, dkek: bytes, shares: list[bytes], member: str, sponsor: str | None,
             lamport: int, flags: int) -> None:
        q = dom.domain_q(dkek)
        md, mpub = member_key(member)
        sponsor_id = dom.member_id(member_key(sponsor)[1]) if sponsor else dom.member_id(mpub)
        cert = dom.issue_cert(dkek, mpub, sponsor_id, lamport, flags)
        assert cert.verify(q)
        assert dom.parse_cert(cert.encode()) == cert
        out.append(f"case {name}")
        if shares:
            out.append("shares " + ",".join(h(s) for s in shares))
        out.append(f"dkek {h(dkek)}")
        out.append(f"kcv {h(dom.kcv(dkek))}")
        out.append(f"okm {h(dom.domain_okm(dkek))}")
        out.append(f"d {dom.domain_scalar(dkek):064x}")
        out.append(f"q {h(q)}")
        out.append(f"domain_id {h(dom.domain_id(q))}")
        out.append(f"member_d {md:064x}")
        out.append(f"member_pub {h(mpub)}")
        out.append(f"member_id {h(dom.member_id(mpub))}")
        out.append(f"sponsor_id {h(sponsor_id)}")
        out.append(f"lamport {lamport}")
        out.append(f"flags {flags:02x}")
        out.append(f"cert {h(cert.encode())}")
        out.append("end")
        out.append("")

    case("kat-shares-self", dom.combine_shares(SHARE1, SHARE2), [SHARE1, SHARE2],
         "A", None, 1, dom.FLAG_MAY_SPONSOR)
    case("kat-shares-sponsored", dom.combine_shares(SHARE1, SHARE2), [SHARE1, SHARE2],
         "B", "A", 7, 0)
    case("dkek-ff", b"\xff" * 32, [b"\x0f" * 32, b"\xf0" * 32], "C", None, 1,
         dom.FLAG_MAY_SPONSOR)
    case("dkek-zero", bytes(32), [], "D", None, 0xFFFF_FFFF_FFFF_FFFE, dom.FLAG_MAY_SPONSOR)
    case("dkek-5c", b"\x5c" * 32, [], "E", "D", 123456789, 1)

    (HERE / "domain_v1.txt").write_text("\n".join(out))
    print(f"wrote {HERE / 'domain_v1.txt'}")


if __name__ == "__main__":
    main()
