#!/usr/bin/env python3
"""Generate the CardContact key-backup known-answer vectors.

Writes `cardcontact_wrap.txt` next to this script, using the independent
Python reference `tools/python/pico2hsm/cardcontact_wrap.py` (not the
firmware).  The firmware test `firmware/tests/cardcontact_wrap_vectors.rs`
reads the file.

RSA keys are generated fresh on every run, so re-running changes the RSA
vectors; the committed file is the reference.  Run with:

    python3 firmware/tests/vectors/gen_cardcontact_wrap.py
"""

from __future__ import annotations

import hashlib
import importlib.util
import pathlib
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

HERE = pathlib.Path(__file__).resolve().parent
REF = HERE.parents[2] / "tools" / "python" / "pico2hsm" / "cardcontact_wrap.py"

# Load the module file directly: the package __init__ pulls in pyscard.
_spec = importlib.util.spec_from_file_location("cardcontact_wrap", REF)
cc = importlib.util.module_from_spec(_spec)
sys.modules["cardcontact_wrap"] = cc
_spec.loader.exec_module(cc)


def h(b: bytes) -> str:
    return b.hex()


SHARE1 = hashlib.sha256(b"pico2hsm KAT DKEK share 1").digest()
SHARE2 = hashlib.sha256(b"pico2hsm KAT DKEK share 2").digest()
DKEK = cc.combine_shares(SHARE1, SHARE2)


def rnd(label: str) -> bytes:
    return hashlib.sha256(b"randomize " + label.encode()).digest()[:8]


def scalar(curve, label: str) -> int:
    v = int.from_bytes(hashlib.sha512(label.encode()).digest() * 2, "big")
    return v % (curve.n - 1) + 1


def main() -> None:
    cc.check_curves()
    out = [
        "# CardContact SmartCard-HSM key-backup blob vectors.",
        "# Generated by gen_cardcontact_wrap.py from the independent Python",
        "# reference tools/python/pico2hsm/cardcontact_wrap.py.  Do not edit.",
        "#",
        "# global: share1, share2 (DKEK = share1 XOR share2), dkek, kcv,",
        "#         kenc, kmac.  Each case: type, input key, randomize, policy",
        "#         fields, blob, and `exact` = 1 when the firmware's WRAP of the",
        "#         same key with the same randomize must produce these bytes.",
        "",
        f"share1 {h(SHARE1)}",
        f"share2 {h(SHARE2)}",
        f"dkek {h(DKEK)}",
        f"kcv {h(cc.kcv(DKEK))}",
        f"kenc {h(cc.k_enc(DKEK))}",
        f"kmac {h(cc.k_mac(DKEK))}",
        "",
    ]

    def case(name, kind, blob, exact, **kv):
        out.append(f"case {name}")
        out.append(f"kind {kind}")
        for k, v in kv.items():
            out.append(f"{k} {v}")
        out.append(f"exact {1 if exact else 0}")
        out.append(f"blob {h(blob)}")
        out.append("end")
        out.append("")

    # --- EC: every curve the firmware supports, canonical encoding ---------
    for name in ("P-256", "P-384", "P-521", "secp256k1"):
        c = cc.CURVES[name]
        d = scalar(c, "ec " + name)
        if name == "P-521":
            # Exercise a scalar shorter than the order: top byte zero.
            d &= (1 << (8 * (c.order_len - 1))) - 1
        size, mat = cc.ec_material(c, d)
        r = rnd(name)
        blob = cc.wrap(DKEK, cc.KEY_TYPE_EC, cc.OID_ECDSA_SHA256, size, mat, r)
        case(f"ec-{name.lower()}", "ec", blob, True, curve=name,
             d=h(d.to_bytes(c.order_len, "big")), q=h(c.point(d)), randomize=h(r),
             algorithms="", access="")

    # --- EC, lenient encoding (pico-hsm style): minimal integers, A of
    #     secp256k1 empty, size = field bytes * 8, no padding when aligned.
    c = cc.CURVES["secp256k1"]
    d = scalar(c, "ec lenient")
    mat = (cc.lv(cc.unsigned(c.a)) + cc.lv(cc.unsigned(c.b)) + cc.lv(cc.unsigned(c.p))
           + cc.lv(cc.unsigned(c.n)) + cc.lv(c.g) + cc.lv(cc.unsigned(d)) + cc.lv(c.point(d)))
    r = rnd("lenient")
    blob = cc.wrap(DKEK, cc.KEY_TYPE_EC, cc.OID_ECDSA_SHA256, c.field_len * 8, mat, r)
    case("ec-secp256k1-minimal", "ec", blob, False, curve="secp256k1",
         d=h(d.to_bytes(32, "big")), q=h(c.point(d)), randomize=h(r), algorithms="", access="")

    # --- EC with an algorithm list that forbids wrap (no 0x92) -------------
    c = cc.CURVES["P-256"]
    d = scalar(c, "ec policy")
    size, mat = cc.ec_material(c, d)
    r = rnd("policy")
    pol = cc.Policy(algorithms=bytes([0x70, 0x73]))
    blob = cc.wrap(DKEK, cc.KEY_TYPE_EC, cc.OID_ECDSA_SHA256, size, mat, r, pol)
    case("ec-p-256-alglist", "ec", blob, False, curve="P-256",
         d=h(d.to_bytes(32, "big")), q=h(c.point(d)), randomize=h(r),
         algorithms="7073", access="")

    # --- EC with pico2hsm key_flags in the access-condition field ----------
    d = scalar(c, "ec flags")
    size, mat = cc.ec_material(c, d)
    r = rnd("flags")
    pol = cc.Policy(access_conditions=bytes([0x03]))
    blob = cc.wrap(DKEK, cc.KEY_TYPE_EC, cc.OID_ECDSA_SHA256, size, mat, r, pol)
    case("ec-p-256-flags", "ec", blob, True, curve="P-256",
         d=h(d.to_bytes(32, "big")), q=h(c.point(d)), randomize=h(r),
         algorithms="", access="03")

    # --- RSA-CRT (what WRAP produces) and plain RSA (pico-hsm's export) ----
    for bits, ktype in ((2048, "rsa-crt"), (1024, "rsa")):
        key = rsa.generate_private_key(public_exponent=65537, key_size=bits)
        der = key.private_bytes(serialization.Encoding.DER,
                                serialization.PrivateFormat.TraditionalOpenSSL,
                                serialization.NoEncryption())
        if ktype == "rsa-crt":
            size, mat = cc.rsa_crt_material(key)
            t, exact = cc.KEY_TYPE_RSA_CRT, True
        else:
            size, mat = cc.rsa_plain_material(key)
            t, exact = cc.KEY_TYPE_RSA, False
        r = rnd(f"rsa {bits}")
        blob = cc.wrap(DKEK, t, cc.OID_RSA_V15_SHA256, size, mat, r)
        pn = key.private_numbers()
        case(f"{ktype}-{bits}", ktype, blob, exact, pkcs1=h(der),
             n=h(cc.unsigned(pn.public_numbers.n)), e=h(cc.unsigned(pn.public_numbers.e)),
             p=h(cc.unsigned(pn.p)), q=h(cc.unsigned(pn.q)), randomize=h(r),
             algorithms="", access="")

    # --- AES-128 / AES-256 --------------------------------------------------
    for n in (16, 24, 32):
        key = hashlib.sha256(f"aes {n}".encode()).digest()[:n]
        size, mat = cc.aes_material(key)
        r = rnd(f"aes {n}")
        blob = cc.wrap(DKEK, cc.KEY_TYPE_AES, cc.OID_AES, size, mat, r)
        case(f"aes-{n * 8}", "aes", blob, True, key=h(key), randomize=h(r),
             algorithms="", access="")

    # Self-check: everything decodes with the reference.
    text = "\n".join(out) + "\n"
    for line in text.splitlines():
        if line.startswith("blob "):
            cc.unwrap(DKEK, bytes.fromhex(line[5:]))
    (HERE / "cardcontact_wrap.txt").write_text(text)
    print("wrote", HERE / "cardcontact_wrap.txt")


if __name__ == "__main__":
    main()
