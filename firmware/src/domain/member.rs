/// Why an imported certificate or revocation was refused.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ImportError {
    /// Malformed (length, version, key, or a member revoking itself).
    Format,
    /// Another domain, or a signature that does not verify.
    Signature,
    /// Already held, or the held one outranks it.
    Duplicate,
    /// The member is revoked (revocation is permanent for a member key),
    /// or the sponsor was revoked before it issued the certificate.
    Revoked,
    /// The member is unknown and no certificate came with the revocation.
    UnknownMember,
    /// The member list is full.
    Full,
    /// The keystore failed.
    Storage,
}

impl ImportError {
    /// The status word reported for it.
    pub fn sw(self) -> u16 {
        match self {
            ImportError::Format | ImportError::Signature => 0x6A80,
            ImportError::Duplicate => SW_ALREADY_HELD,
            ImportError::Revoked => 0x6984,
            ImportError::UnknownMember => SW_UNKNOWN_MEMBER,
            ImportError::Full => SW_LIST_FULL,
            ImportError::Storage => 0x6581,
        }
    }
}

impl From<HsmError> for ImportError {
    fn from(_: HsmError) -> Self {
        ImportError::Storage
    }
}

impl From<CertError> for ImportError {
    fn from(e: CertError) -> Self {
        match e {
            CertError::Format | CertError::MemberKey => ImportError::Format,
            CertError::Signature => ImportError::Signature,
        }
    }
}

/// SW: already held (`6A89`, "file already exists").
pub const SW_ALREADY_HELD: u16 = 0x6A89;
/// SW: the member is not in the list (`6A88`, "referenced data not found").
pub const SW_UNKNOWN_MEMBER: u16 = 0x6A88;
/// SW: the member list is full (`6A84`, "not enough memory space").
pub const SW_LIST_FULL: u16 = 0x6A84;

/// What an import did: the slot, and whether the member is new to the list.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Imported {
    pub slot: u8,
    pub added: bool,
}

/// Import a member certificate (no PIN: authority is the domain
/// signature, §12.1).  Refused: another domain or a bad signature; a
/// certificate already held or outranked by the held one ([`outranks`]);
/// a revoked member, whatever the certificate's age; a certificate whose
/// sponsor was revoked before it issued it (§6.4); a full list.
#[inline(never)]
pub fn import_cert(
    store: &mut dyn KeyStore,
    q_domain: &[u8; 65],
    bytes: &[u8],
) -> Result<Imported, ImportError> {
    let cert = MemberCert::decode(bytes)?;
    cert.verify(q_domain)?;
    if !cert.is_self_issued() {
        if let Lookup::Found(_, sponsor) = lookup(store, &cert.sponsor_id)? {
            if sponsor
                .revocation
                .as_ref()
                .is_some_and(|r| cert.issued_lamport > r.revoked_lamport)
            {
                return Err(ImportError::Revoked);
            }
        }
    }
    let (slot, added) = match lookup(store, &cert.member_id)? {
        Lookup::Found(_, held) if held.revocation.is_some() => return Err(ImportError::Revoked),
        Lookup::Found(slot, held) => {
            if !outranks(&cert, &held.cert) {
                return Err(ImportError::Duplicate);
            }
            (slot, false)
        }
        Lookup::Free(slot) => (slot, true),
        Lookup::Full => return Err(ImportError::Full),
    };
    save(store, slot, &MemberEntry::active(cert))?;
    Ok(Imported { slot, added })
}

/// Import a revocation, optionally with the revoked member's certificate
/// (needed when the member is not listed yet, so the list can refuse its
/// certificates from now on).  Of two revocations of one member the
/// earliest is kept ([`Revocation::precedes`]).
#[inline(never)]
pub fn import_revocation(
    store: &mut dyn KeyStore,
    q_domain: &[u8; 65],
    bytes: &[u8],
    cert: Option<&[u8]>,
) -> Result<Imported, ImportError> {
    let rev = Revocation::decode(bytes)?;
    rev.verify(q_domain)?;
    match lookup(store, &rev.member_id)? {
        Lookup::Found(slot, mut held) => {
            if held
                .revocation
                .as_ref()
                .is_some_and(|old| !rev.precedes(old))
            {
                return Err(ImportError::Duplicate);
            }
            held.revocation = Some(rev);
            save(store, slot, &held)?;
            Ok(Imported { slot, added: false })
        }
        Lookup::Free(slot) => {
            let Some(cert) = cert else {
                return Err(ImportError::UnknownMember);
            };
            let cert = MemberCert::decode(cert)?;
            cert.verify(q_domain)?;
            if cert.member_id != rev.member_id {
                return Err(ImportError::Format);
            }
            save(
                store,
                slot,
                &MemberEntry {
                    cert,
                    revocation: Some(rev),
                },
            )?;
            Ok(Imported { slot, added: true })
        }
        Lookup::Full if cert.is_none() => Err(ImportError::UnknownMember),
        Lookup::Full => Err(ImportError::Full),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn member_pub(seed: u8) -> [u8; 65] {
        use p256::elliptic_curve::sec1::ToEncodedPoint;
        let sk = p256::SecretKey::from_slice(&[seed; 32]).unwrap();
        let mut out = [0u8; 65];
        out.copy_from_slice(sk.public_key().to_encoded_point(false).as_bytes());
        out
    }

    #[test]
    fn issued_certificate_round_trips_and_verifies() {
        let domain = DomainKey::derive(&[7; 32]).unwrap();
        let pubk = member_pub(3);
        let id = member_id(&pubk);
        let cert = MemberCert::issue(&domain, &pubk, &id, 42, FLAG_MAY_SPONSOR).unwrap();
        let bytes = cert.encode();
        assert_eq!(bytes.len(), 187);
        let back = MemberCert::decode(&bytes).unwrap();
        assert_eq!(back, cert);
        assert_eq!(back.verify(&domain.q), Ok(()));

        let other = DomainKey::derive(&[8; 32]).unwrap();
        assert_eq!(back.verify(&other.q), Err(CertError::Signature));

        let mut tampered = bytes;
        tampered[121] ^= 1; // issued_lamport
        assert_eq!(
            MemberCert::decode(&tampered).unwrap().verify(&domain.q),
            Err(CertError::Signature)
        );
        let mut wrong_id = bytes;
        wrong_id[17] ^= 1;
        assert_eq!(MemberCert::decode(&wrong_id), Err(CertError::MemberKey));
        assert_eq!(MemberCert::decode(&bytes[..186]), Err(CertError::Format));
    }

    #[test]
    fn entries_round_trip() {
        let domain = DomainKey::derive(&[7; 32]).unwrap();
        let pubk = member_pub(5);
        let cert = MemberCert::issue(&domain, &pubk, &member_id(&pubk), 1, 0).unwrap();
        let mut e = MemberEntry::active(cert);
        let b = e.encode();
        assert_eq!(b.len(), ENTRY_V2_LEN);
        assert_eq!(b[0], ENTRY_V2_VERSION);
        assert_eq!(MemberEntry::decode(&b).unwrap(), e);
        // P1 entries (version 1) still load.
        let v1 = e.encode_v1();
        assert_eq!((v1.len(), v1[0]), (ENTRY_LEN, ENTRY_VERSION));
        assert_eq!(&v1[1..], &b[1..ENTRY_LEN], "v2 extends v1");
        assert_eq!(MemberEntry::decode(&v1).unwrap(), e);
        let mut bad = b;
        bad[1] = 9;
        assert_eq!(MemberEntry::decode(&bad), Err(CertError::Format));

        // A revoked entry carries the whole revocation.
        let revoker = member_id(&member_pub(6));
        let rev = Revocation::issue(&domain, &e.cert.member_id, &revoker, 9).unwrap();
        e.revocation = Some(rev.clone());
        let b = e.encode();
        let back = MemberEntry::decode(&b).unwrap();
        assert_eq!(back.status(), STATUS_REVOKED);
        assert_eq!(back.revoked_lamport(), 9);
        assert_eq!(back.revocation.as_ref().unwrap().encode(), rev.encode());
        assert_eq!(back.revocation.unwrap().verify(&domain.q), Ok(()));
        // A version-1 entry cannot say "revoked" (it has no revocation).
        let mut v1 = e.encode_v1();
        assert_eq!(v1[1], STATUS_REVOKED);
        assert_eq!(MemberEntry::decode(&v1), Err(CertError::Format));
        v1[1] = STATUS_ACTIVE;
        assert!(MemberEntry::decode(&v1).is_ok());
    }

    #[test]
    fn revocations_round_trip_and_verify() {
        let domain = DomainKey::derive(&[7; 32]).unwrap();
        let (a, b) = (member_id(&member_pub(1)), member_id(&member_pub(2)));
        let rev = Revocation::issue(&domain, &a, &b, 77).unwrap();
        let bytes = rev.encode();
        assert_eq!(bytes.len(), REVOCATION_LEN);
        let back = Revocation::decode(&bytes).unwrap();
        assert_eq!(back, rev);
        assert_eq!(back.verify(&domain.q), Ok(()));
        let other = DomainKey::derive(&[8; 32]).unwrap();
        assert_eq!(back.verify(&other.q), Err(CertError::Signature));
        let mut tampered = bytes;
        tampered[56] ^= 1; // revoked_lamport
        assert_eq!(
            Revocation::decode(&tampered).unwrap().verify(&domain.q),
            Err(CertError::Signature)
        );
        assert!(
            Revocation::issue(&domain, &a, &a, 1).is_err(),
            "no self-revocation"
        );
        let mut selfrev = bytes;
        selfrev[33..49].copy_from_slice(&a);
        assert_eq!(Revocation::decode(&selfrev), Err(CertError::Format));
        assert_eq!(Revocation::decode(&bytes[..120]), Err(CertError::Format));

        let later = Revocation::issue(&domain, &a, &b, 78).unwrap();
        assert!(rev.precedes(&later) && !later.precedes(&rev));
        assert!(!rev.precedes(&rev));
    }

    #[test]
    fn sponsor_issued_outranks_self_issued_then_lamport() {
        let domain = DomainKey::derive(&[7; 32]).unwrap();
        let pubk = member_pub(4);
        let id = member_id(&pubk);
        let sponsor = member_id(&member_pub(9));
        let self_hi = MemberCert::issue(&domain, &pubk, &id, 1000, 1).unwrap();
        let spons_lo = MemberCert::issue(&domain, &pubk, &sponsor, 3, 0).unwrap();
        let spons_hi = MemberCert::issue(&domain, &pubk, &sponsor, 4, 1).unwrap();
        assert!(outranks(&spons_lo, &self_hi));
        assert!(!outranks(&self_hi, &spons_lo));
        assert!(outranks(&spons_hi, &spons_lo));
        assert!(!outranks(&spons_lo, &spons_hi));
        assert!(!outranks(&spons_hi, &spons_hi), "equal never outranks");
    }
}
