/// Revocation record format version.
pub const REVOCATION_VERSION: u8 = 1;
/// Signed part of a revocation.
pub const REVOCATION_BODY_LEN: usize = 57;
/// Whole revocation record.
pub const REVOCATION_LEN: usize = REVOCATION_BODY_LEN + 64;
/// Domain-separation prefix of the revocation signature input.
pub const REVOCATION_CONTEXT: &[u8] = b"pico2hsm-member-revoke-v1";

/// A member revocation (cluster plan V3 §6.4), signed with the domain key.
///
/// ```text
/// [0]       version          1
/// [1..17]   domain_id
/// [17..33]  member_id        the revoked member
/// [33..49]  revoker_id       the member that revoked it (never itself)
/// [49..57]  revoked_lamport  u64 BE, the revoker's Lamport counter
/// [57..121] sig_domain       ECDSA-P256(d_domain, r || s) over
///                            SHA-256("pico2hsm-member-revoke-v1" || [0..57])
/// ```
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Revocation {
    pub domain_id: [u8; DOMAIN_ID_LEN],
    pub member_id: [u8; MEMBER_ID_LEN],
    pub revoker_id: [u8; MEMBER_ID_LEN],
    pub revoked_lamport: u64,
    pub sig: [u8; 64],
}

impl Revocation {
    /// The signed fields, `[0..57]`.
    pub fn body(&self) -> [u8; REVOCATION_BODY_LEN] {
        let mut b = [0u8; REVOCATION_BODY_LEN];
        b[0] = REVOCATION_VERSION;
        b[1..17].copy_from_slice(&self.domain_id);
        b[17..33].copy_from_slice(&self.member_id);
        b[33..49].copy_from_slice(&self.revoker_id);
        b[49..57].copy_from_slice(&self.revoked_lamport.to_be_bytes());
        b
    }

    /// `SHA-256(REVOCATION_CONTEXT || body)`, the digest the domain key signs.
    pub fn digest(body: &[u8; REVOCATION_BODY_LEN]) -> [u8; 32] {
        let mut h = Sha256::new();
        h.update(REVOCATION_CONTEXT);
        h.update(body);
        h.finalize().into()
    }

    /// The 121-byte encoding.
    pub fn encode(&self) -> [u8; REVOCATION_LEN] {
        let mut out = [0u8; REVOCATION_LEN];
        out[..REVOCATION_BODY_LEN].copy_from_slice(&self.body());
        out[REVOCATION_BODY_LEN..].copy_from_slice(&self.sig);
        out
    }

    /// Parse a revocation.  A member that revokes itself is malformed.
    pub fn decode(b: &[u8]) -> Result<Self, CertError> {
        if b.len() != REVOCATION_LEN || b[0] != REVOCATION_VERSION {
            return Err(CertError::Format);
        }
        let take16 = |at: usize| {
            let mut a = [0u8; 16];
            a.copy_from_slice(&b[at..at + 16]);
            a
        };
        let rev = Revocation {
            domain_id: take16(1),
            member_id: take16(17),
            revoker_id: take16(33),
            revoked_lamport: u64::from_be_bytes(b[49..57].try_into().unwrap_or([0; 8])),
            sig: b[REVOCATION_BODY_LEN..].try_into().unwrap_or([0; 64]),
        };
        if rev.member_id == rev.revoker_id {
            return Err(CertError::Format);
        }
        Ok(rev)
    }

    /// Check that the revocation belongs to the domain of `q_domain` and
    /// that `sig_domain` verifies under it.
    pub fn verify(&self, q_domain: &[u8; 65]) -> Result<(), CertError> {
        if self.domain_id != domain_id(q_domain)
            || !verify_prehash(q_domain, &Self::digest(&self.body()), &self.sig)
        {
            return Err(CertError::Signature);
        }
        Ok(())
    }

    /// Issue (sign) a revocation of `member_id` by `revoker_id`.
    pub fn issue(
        domain: &DomainKey,
        member_id: &[u8; MEMBER_ID_LEN],
        revoker_id: &[u8; MEMBER_ID_LEN],
        revoked_lamport: u64,
    ) -> Result<Self, ()> {
        if member_id == revoker_id {
            return Err(());
        }
        let mut rev = Revocation {
            domain_id: domain.id,
            member_id: *member_id,
            revoker_id: *revoker_id,
            revoked_lamport,
            sig: [0u8; 64],
        };
        rev.sig = domain.sign_prehash(&Self::digest(&rev.body()))?;
        Ok(rev)
    }

    /// Of two revocations of the same member every device keeps the
    /// earliest — lowest `(revoked_lamport, revoker_id, sig)` — so the
    /// lists converge whatever order revocations arrive in.  (The earlier
    /// one refuses more of the member's later records, §6.4.)
    pub fn precedes(&self, other: &Revocation) -> bool {
        (self.revoked_lamport, self.revoker_id, self.sig)
            < (other.revoked_lamport, other.revoker_id, other.sig)
    }
}

/// Of two valid certificates for the same member every device keeps the
/// same one: a sponsor-issued certificate outranks a self-issued one
/// (§4.4: the sponsor's replaces the self certificate a joiner gives
/// itself when the DKEK arrives), then the higher `issued_lamport` wins (a
/// re-issue), then the larger encoding (a tie only a fault could cause).
pub fn outranks(new: &MemberCert, old: &MemberCert) -> bool {
    let key = |c: &MemberCert| (!c.is_self_issued(), c.issued_lamport);
    match key(new).cmp(&key(old)) {
        core::cmp::Ordering::Greater => true,
        core::cmp::Ordering::Less => false,
        core::cmp::Ordering::Equal => new.encode() > old.encode(),
    }
}

impl MemberCert {
    /// Self-issued (the member sponsored itself).
    pub fn is_self_issued(&self) -> bool {
        self.sponsor_id == self.member_id
    }

    /// Whether the member may sponsor (and so administer) others.
    pub fn may_sponsor(&self) -> bool {
        self.flags & FLAG_MAY_SPONSOR != 0
    }
}

