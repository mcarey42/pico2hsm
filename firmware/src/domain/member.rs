/// One member-list entry: the member's certificate and, once it is
/// revoked, the revocation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MemberEntry {
    pub cert: MemberCert,
    pub revocation: Option<Revocation>,
}

impl MemberEntry {
    /// An active entry for `cert`.
    pub fn active(cert: MemberCert) -> Self {
        MemberEntry {
            cert,
            revocation: None,
        }
    }

    /// [`STATUS_ACTIVE`] or [`STATUS_REVOKED`].
    pub fn status(&self) -> u8 {
        if self.revocation.is_some() {
            STATUS_REVOKED
        } else {
            STATUS_ACTIVE
        }
    }

    /// The revocation's Lamport value, 0 while active.
    pub fn revoked_lamport(&self) -> u64 {
        self.revocation.as_ref().map_or(0, |r| r.revoked_lamport)
    }

    /// Active and allowed to sponsor: may issue and revoke certificates.
    pub fn may_administer(&self) -> bool {
        self.revocation.is_none() && self.cert.may_sponsor()
    }

    /// The version-1 (P1) wire encoding, 197 bytes, without the revocation
    /// record (GET_MEMBERS v1).
    pub fn encode_v1(&self) -> [u8; ENTRY_LEN] {
        let mut out = [0u8; ENTRY_LEN];
        out[0] = ENTRY_VERSION;
        out[1] = self.status();
        out[2..10].copy_from_slice(&self.revoked_lamport().to_be_bytes());
        out[10..].copy_from_slice(&self.cert.encode());
        out
    }

    /// The stored / GET_MEMBERS v2 encoding, 277 bytes.
    pub fn encode(&self) -> [u8; ENTRY_V2_LEN] {
        let mut out = [0u8; ENTRY_V2_LEN];
        out[..ENTRY_LEN].copy_from_slice(&self.encode_v1());
        out[0] = ENTRY_V2_VERSION;
        if let Some(r) = &self.revocation {
            out[ENTRY_LEN..ENTRY_LEN + 16].copy_from_slice(&r.revoker_id);
            out[ENTRY_LEN + 16..].copy_from_slice(&r.sig);
        }
        out
    }

    /// Parse an entry: version 2 (277 bytes), or version 1 (197 bytes,
    /// written by P1, active only).
    pub fn decode(b: &[u8]) -> Result<Self, CertError> {
        let v2 = match (b.first(), b.len()) {
            (Some(&ENTRY_VERSION), ENTRY_LEN) => false,
            (Some(&ENTRY_V2_VERSION), ENTRY_V2_LEN) => true,
            _ => return Err(CertError::Format),
        };
        let cert = MemberCert::decode(&b[10..ENTRY_LEN])?;
        let revoked_lamport = u64::from_be_bytes(b[2..10].try_into().unwrap_or([0; 8]));
        let revocation = match b[1] {
            STATUS_ACTIVE => None,
            STATUS_REVOKED if v2 => {
                let mut revoker_id = [0u8; MEMBER_ID_LEN];
                revoker_id.copy_from_slice(&b[ENTRY_LEN..ENTRY_LEN + 16]);
                let mut sig = [0u8; 64];
                sig.copy_from_slice(&b[ENTRY_LEN + 16..]);
                Some(Revocation {
                    domain_id: cert.domain_id,
                    member_id: cert.member_id,
                    revoker_id,
                    revoked_lamport,
                    sig,
                })
            }
            _ => return Err(CertError::Format),
        };
        Ok(MemberEntry { cert, revocation })
    }
}

