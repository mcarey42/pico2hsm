//! Renderers for the generated artefacts: `memory.x` and the picotool
//! partition-table JSON.  Hand-built strings; no dependencies.

use crate::Profile;
use std::fmt::Write;
use std::string::String;

const FLASH_BASE: u32 = 0x1000_0000;
const BOOT2_LEN: u32 = 0x100;
const RAM_LEN: u32 = 0x82000;

/// Which table to render.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Table {
    /// Development: the unpartitioned space is open (`rw/rw/rw`).
    Dev,
    /// Production: the unpartitioned space is closed (`rw//r`).
    Prod,
}

/// File name of the table under `boards/`.
pub fn table_file_name(p: &Profile, t: Table) -> &'static str {
    match (p.name, t) {
        ("4m", Table::Dev) => "pt_4m.json",
        ("4m", Table::Prod) => "pt_4m_prod.json",
        ("16m", Table::Dev) => "pt_16m.json",
        ("16m", Table::Prod) => "pt_16m_prod.json",
        _ => panic!("unknown profile"),
    }
}

/// Render a profile's `memory.x`.
pub fn memory_x(p: &Profile) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "/* memory.x for the {} MB flash profile.\n * Generated by pico2hsm-layout; do not edit. */\n",
        p.name.trim_end_matches('m')
    );
    s.push_str("MEMORY {\n");
    let mut line = |name: &str, origin: u32, len: u32| {
        let _ = writeln!(
            s,
            "    {name:<8} : ORIGIN = {origin:#010X}, LENGTH = {len:#X}"
        );
    };
    line("BOOT2", FLASH_BASE, BOOT2_LEN);
    line("FLASH", FLASH_BASE + BOOT2_LEN, p.slot_size - BOOT2_LEN);
    let mut off = p.store_base;
    for r in p.regions {
        line(r.name, FLASH_BASE + off, r.size);
        off += r.size;
    }
    line(
        "KEYSTORE",
        FLASH_BASE + p.keystore_start,
        p.keystore_end - p.keystore_start,
    );
    line("RAM", 0x2000_0000, RAM_LEN);
    s.push_str(
        "}\n\n/* Place the RP2350 IMAGE_DEF block at the very beginning of flash. */\nSECTIONS {\n    .boot2 : {\n        KEEP(*(.start_block .start_block.*))\n    } > BOOT2\n}\n",
    );
    s
}

fn perms(s: &mut String, indent: &str, secure: &str, ns: &str, boot: &str) {
    let _ = write!(
        s,
        "{indent}\"permissions\": {{\n{indent}    \"secure\": \"{secure}\",\n{indent}    \"nonsecure\": \"{ns}\",\n{indent}    \"bootloader\": \"{boot}\"\n{indent}}}"
    );
}

fn partition(s: &mut String, name: &str, id: u8, start: u32, size: u32, fw: bool, link: bool) {
    let family = if fw { "rp2350-arm-s" } else { "data" };
    let _ = write!(
        s,
        "        {{\n            \"name\": \"{name}\",\n            \"id\": {id},\n            \"start\": \"{}K\",\n            \"size\": \"{}K\",\n            \"families\": [\n                \"{family}\"\n            ],\n",
        start / 1024,
        size / 1024
    );
    if fw {
        perms(s, "            ", "rw", "rw", "rw");
    } else {
        perms(s, "            ", "rw", "", "");
    }
    if link {
        s.push_str(
            ",\n            \"link\": [\n                \"a\",\n                0\n            ]",
        );
    }
    if !fw {
        s.push_str(",\n            \"ignored_during_arm_boot\": true,\n            \"ignored_during_riscv_boot\": true");
    }
    s.push_str("\n        }");
}

/// Render a profile's partition table.
pub fn partition_json(p: &Profile, t: Table) -> String {
    let mut s = String::from(
        "{\n    \"$schema\": \"https://raw.githubusercontent.com/raspberrypi/picotool/develop/json/schemas/partition-table-schema.json\",\n    \"version\": [\n        1,\n        0\n    ],\n    \"unpartitioned\": {\n        \"families\": [\n            \"absolute\"\n        ],\n",
    );
    match t {
        Table::Dev => perms(&mut s, "        ", "rw", "rw", "rw"),
        Table::Prod => perms(&mut s, "        ", "rw", "", "r"),
    }
    s.push_str("\n    },\n    \"partitions\": [\n");
    partition(&mut s, "fw-a", 0, crate::SLOT_A, p.slot_size, true, false);
    if p.slot_b != 0 {
        s.push_str(",\n");
        partition(&mut s, "fw-b", 1, p.slot_b, p.slot_size, true, true);
    }
    let mut off = p.store_base;
    for r in p.regions {
        s.push_str(",\n");
        partition(&mut s, r.partition, r.id, off, r.size, false, false);
        off += r.size;
    }
    s.push_str(",\n");
    partition(
        &mut s,
        "keystore",
        crate::KEYSTORE_ID,
        p.keystore_start,
        p.keystore_end - p.keystore_start,
        false,
        false,
    );
    s.push_str("\n    ]\n}\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{PROFILE_16M, PROFILE_4M};
    use std::vec::Vec;

    fn regions(x: &str) -> Vec<(String, u64, u64)> {
        x.lines()
            .filter(|l| l.contains("ORIGIN"))
            .map(|l| {
                let (name, rest) = l.split_once(':').unwrap();
                let (o, len) = rest.split_once("LENGTH").unwrap();
                let o = o.split('=').nth(1).unwrap().trim().trim_end_matches(',');
                let len = len.trim_start_matches([' ', '=']).trim();
                let h = |v: &str| u64::from_str_radix(v.trim_start_matches("0x"), 16).unwrap();
                (name.trim().into(), h(o), h(len))
            })
            .collect()
    }
    fn golden(v: &[(&str, u64, u64)]) -> Vec<(String, u64, u64)> {
        v.iter().map(|(n, o, l)| ((*n).into(), *o, *l)).collect()
    }

    #[test]
    fn memory_x_regions_match_the_shipped_scripts() {
        assert_eq!(
            regions(&memory_x(&PROFILE_4M)),
            golden(&[
                ("BOOT2", 0x1000_0000, 0x100),
                ("FLASH", 0x1000_0100, 0x1D_5F00),
                ("BINDING", 0x101D_8000, 0x8000),
                ("RETRY_COUNTERS", 0x101E_0000, 0x10000),
                ("RSA_POOL", 0x101F_0000, 0xC000),
                ("LEGACY_COUNTERS", 0x101F_C000, 0x4000),
                ("KEYSTORE", 0x1020_1000, 0x1F_F000),
                ("RAM", 0x2000_0000, 0x82000),
            ])
        );
        assert_eq!(
            regions(&memory_x(&PROFILE_16M)),
            golden(&[
                ("BOOT2", 0x1000_0000, 0x100),
                ("FLASH", 0x1000_0100, 0x3F_DF00),
                ("BINDING", 0x1080_1000, 0x8000),
                ("RETRY_COUNTERS", 0x1080_9000, 0x10000),
                ("RSA_POOL", 0x1081_9000, 0xC000),
                ("LEGACY_COUNTERS", 0x1082_5000, 0x4000),
                ("KEYSTORE", 0x1082_9000, 0x7D_6000),
                ("RAM", 0x2000_0000, 0x82000),
            ])
        );
    }

    #[test]
    fn memory_x_keeps_the_start_block_section() {
        assert!(memory_x(&PROFILE_4M).contains("KEEP(*(.start_block .start_block.*))"));
    }

    #[test]
    fn partition_json_is_byte_identical_to_the_committed_tables() {
        assert_eq!(
            partition_json(&PROFILE_4M, Table::Dev),
            include_str!("../../boards/pt_4m.json")
        );
        assert_eq!(
            partition_json(&PROFILE_4M, Table::Prod),
            include_str!("../../boards/pt_4m_prod.json")
        );
        assert_eq!(
            partition_json(&PROFILE_16M, Table::Dev),
            include_str!("../../boards/pt_16m.json")
        );
        assert_eq!(
            partition_json(&PROFILE_16M, Table::Prod),
            include_str!("../../boards/pt_16m_prod.json")
        );
    }

    #[test]
    fn table_file_names() {
        assert_eq!(table_file_name(&PROFILE_4M, Table::Prod), "pt_4m_prod.json");
        assert_eq!(table_file_name(&PROFILE_16M, Table::Dev), "pt_16m.json");
    }
}
