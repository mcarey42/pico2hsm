# Test 1: Key survives reboot (flash service channel validation)
# ---------------------------------------------------------------------------

class TestKeyPersistence:
    """Generated key must survive a device reset (flash persistence)."""

    def test_key_survives_reboot(
        self,
        runner: CLIRunner,
        config: dict,
    ) -> None:
        """After GENERATE KEY PAIR + reset, the key must still be usable for signing."""
        # 1. Initialize device
        _initialize_device(config)

        # 2. Generate a P-256 key via pkcs11-tool
        keygen = runner.pkcs11_tool(
            "--login",
            "--pin", config["pin"],
            "--keypairgen",
            "--key-type", "EC:prime256v1",
            "--id", "20",
            "--label", "persist-test",
            save_as="14_persist_keygen",
        )
        assert keygen.returncode == 0, (
            f"Key generation failed: rc={keygen.returncode}\n{keygen.stderr}"
        )
        log.info("P-256 key generated (id=20)")

        # 3. Sign something before reset to confirm the key works
        import tempfile
        with tempfile.NamedTemporaryFile(suffix=".bin", delete=False) as f:
            f.write(b"persistence test message before reset")
            msg_path = f.name
        with tempfile.NamedTemporaryFile(suffix=".sig", delete=False) as f:
            sig_path_pre = f.name

        sign_pre = runner.pkcs11_tool(
            "--login",
            "--pin", config["pin"],
            "--sign",
            "--mechanism", "ECDSA-SHA256",
            "--id", "20",
            "--input-file", msg_path,
            "--output-file", sig_path_pre,
            save_as="14_persist_sign_pre_reset",
        )
        assert sign_pre.returncode == 0, (
            f"Pre-reset sign failed: rc={sign_pre.returncode}\n{sign_pre.stderr}"
        )
        log.info("Pre-reset sign succeeded")

        # 4. Reset device
        _reset_device()

        # 5. Sign with the same key after reset
        with tempfile.NamedTemporaryFile(suffix=".sig", delete=False) as f:
            sig_path_post = f.name

        sign_post = runner.pkcs11_tool(
            "--login",
            "--pin", config["pin"],
            "--sign",
            "--mechanism", "ECDSA-SHA256",
            "--id", "20",
            "--input-file", msg_path,
            "--output-file", sig_path_post,
            save_as="14_persist_sign_post_reset",
        )
        assert sign_post.returncode == 0, (
            f"Post-reset sign failed -- key did not survive reboot: "
            f"rc={sign_post.returncode}\n{sign_post.stderr}"
        )
        log.info("Post-reset sign succeeded -- key persisted across reboot")

        # Clean up temp files
        import os as _os
        for p in (msg_path, sig_path_pre, sig_path_post):
            try:
                _os.unlink(p)
            except OSError:
                pass


