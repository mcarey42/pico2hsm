"""Hardware integration tests for flash persistence across device reboot.

Validates three newly implemented features:

1. **Flash service channel** -- Keys generated by GENERATE KEY PAIR are now
   persisted to flash.  After a probe-rs reset (simulating power cycle), the
   key must still be usable for signing.

2. **key_flags persistence** -- The NO_EXPORT flag (TLV tag 0xD4 = 0x08) is
   stored alongside the key in flash.  After a reboot, exporting a key that
   was generated with NO_EXPORT must still be rejected (SW=6985).

3. **PIN persistence** -- User PIN and SO-PIN set during INITIALIZE are stored
   in flash.  After a reboot, VERIFY with the correct PIN must succeed and
   VERIFY with the wrong PIN must be rejected.

Each test is self-contained: it initializes the device, generates state, resets
the hardware via probe-rs, waits for USB re-enumeration, and then checks that
the expected state survived the reset.

Requires:
  - Physical pico2hsm device connected via Debugprobe (CMSIS-DAP)
  - probe-rs installed and in PATH
  - pcscd running
"""

from __future__ import annotations

import logging
import os
import re
import subprocess
import time

import pytest

from helpers.cli import CLIRunner

log = logging.getLogger(__name__)

pytestmark = pytest.mark.hw

# ---------------------------------------------------------------------------
# APDU constants
# ---------------------------------------------------------------------------
SELECT_SC_HSM = "00A404000BE82B0601040181C31F020100"

# P-256 GENERATE KEY PAIR APDU data.
#
# Minimal TLV that the firmware's generate_keypair handler accepts:
#   5F29 01 00        -- CPI = 0x00 (infer algorithm from params)
#   7F49 <len>        -- public key template
#     85 20 <order>   -- P-256 group order (32 bytes) -> algo=0x13
#
# The firmware infers P-256 from the 32-byte order via algo_from_order_tag().
# We provide the standard P-256 order so it matches, not K-256.
P256_ORDER_HEX = (
    "FFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551"
)


def _p256_keygen_data(key_flags: int = 0x00) -> str:
    """Build the TLV command data for GENERATE KEY PAIR (P-256).

    Optionally includes tag 0xD4 with the given key_flags byte.
    """
    # 7F49 block: tag 85 (order) with 32-byte P-256 order
    inner_7f49 = f"8520{P256_ORDER_HEX}"
    inner_7f49_len = len(bytes.fromhex(inner_7f49))
    pk_template = f"7F49{inner_7f49_len:02X}{inner_7f49}"

    # 5F29 01 00 = Certificate Profile Identifier
    cpi = "5F290100"

    if key_flags != 0x00:
        flags_tlv = f"D401{key_flags:02X}"  # tag D4, length 01, value
        return cpi + pk_template + flags_tlv
    else:
        return cpi + pk_template


# USB re-enumeration wait after probe-rs reset
REBOOT_WAIT_SECS = int(os.environ.get("PERSISTENCE_REBOOT_WAIT", "12"))


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _wait_for_device(timeout: float = 25.0) -> bool:
    """Poll until pcscd reports a card present and accessible."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            r = subprocess.run(
                ["opensc-tool", "--list-readers"],
                capture_output=True, timeout=5,
            )
            if r.returncode == 0 and b"Yes" in r.stdout:
                log.info("Device card detected and accessible by pcscd.")
                return True
        except (subprocess.TimeoutExpired, FileNotFoundError):
            pass
        time.sleep(0.5)
    log.warning("Device did not appear within %.0f s.", timeout)
    return False


def _reset_device() -> None:
    """Reset the device via probe-rs and wait for USB re-enumeration."""
    log.info("Resetting device via probe-rs...")
    result = subprocess.run(
        ["probe-rs", "reset", "--chip", "RP235x"],
        capture_output=True, timeout=15,
    )
    if result.returncode != 0:
        log.warning(
            "probe-rs reset returned rc=%d: %s",
            result.returncode,
            result.stderr.decode(errors="replace"),
        )
    log.info("Waiting %d s for USB re-enumeration...", REBOOT_WAIT_SECS)
    time.sleep(REBOOT_WAIT_SECS)
    if not _wait_for_device(timeout=25.0):
        pytest.fail("Device did not re-enumerate after probe-rs reset")


def _initialize_device(config: dict) -> None:
    """INITIALIZE the device with known SO-PIN and User PIN."""
    result = subprocess.run(
        [
            "sc-hsm-tool",
            "--initialize",
            "--label", config["label"],
            "--so-pin", config["so_pin"],
            "--pin", config["pin"],
        ],
        capture_output=True, timeout=60,
    )
    assert result.returncode == 0, (
        f"INITIALIZE failed: rc={result.returncode}\n"
        f"{result.stderr.decode(errors='replace')}"
    )
    log.info("Device initialized (so_pin=%s, pin=%s)", config["so_pin"], config["pin"])
    assert _wait_for_device(timeout=25.0), "Device did not re-enumerate after INITIALIZE"


def _initialize_with_dkek(config: dict, dkek_shares: int = 1) -> None:
    """Initialize the device with DKEK shares enabled."""
    result = subprocess.run(
        [
            "sc-hsm-tool",
            "--initialize",
            "--label", config["label"],
            "--so-pin", config["so_pin"],
            "--pin", config["pin"],
            "--dkek-shares", str(dkek_shares),
        ],
        capture_output=True, timeout=60,
    )
    assert result.returncode == 0, (
        f"INITIALIZE with dkek-shares={dkek_shares} failed: "
        f"{result.stderr.decode(errors='replace')}"
    )
    log.info("Device initialized with dkek-shares=%d", dkek_shares)
    assert _wait_for_device(timeout=25.0), "Device did not re-enumerate after INITIALIZE"


def _parse_sw(opensc_output: str) -> list[int]:
    """Return list of status words from all Received lines."""
    sws = []
    for line in opensc_output.splitlines():
        m = re.search(r'Received.*SW1=0x([0-9A-Fa-f]+).*SW2=0x([0-9A-Fa-f]+)', line)
        if m:
            sws.append((int(m.group(1), 16) << 8) | int(m.group(2), 16))
    return sws


def _last_sw(opensc_output: str) -> int:
    """Return the last status word from the output, or 0 if none found."""
    sws = _parse_sw(opensc_output)
    return sws[-1] if sws else 0


def _verify_pin_apdu(pin: str) -> str:
    """Build a VERIFY User PIN APDU from an ASCII PIN string."""
    pin_bytes = pin.encode()
    return f"00200081{len(pin_bytes):02X}{pin_bytes.hex()}"


def _verify_sopin_apdu(so_pin: str) -> str:
    """Build a VERIFY SO-PIN APDU.

    sc-hsm-tool encodes --so-pin as a 16-char hex string representing 8 raw
    bytes.  VERIFY must send those same 8 raw bytes (P2=0x88 selects SO-PIN).
    """
    try:
        so_bytes = bytes.fromhex(so_pin)
    except ValueError:
        so_bytes = so_pin.encode()
    return f"00200088{len(so_bytes):02X}{so_bytes.hex()}"


def _build_keygen_apdu(key_ref: int, data_hex: str) -> str:
    """Build a GENERATE KEY PAIR APDU (INS=0x46) using short APDU encoding.

    The P-256 keygen TLV payload is ~44 bytes, well within the 255-byte short
    APDU limit.  Use short format (1-byte Lc) to avoid ambiguity: the firmware
    APDU parser treats a leading 0x00 at byte[4] as Lc=0 (short) rather than
    the extended-APDU indicator, so extended APDUs sent via opensc-tool -s
    would silently lose their data.
    """
    data_bytes = bytes.fromhex(data_hex)
    lc = len(data_bytes)
    assert lc <= 255, f"Data too large for short APDU: {lc} bytes"
    # Short APDU: CLA INS P1 P2 Lc <data> Le
    # Le=00 requests up to 256 bytes of response (the public key TLV).
    return f"0046{key_ref:02X}00{lc:02X}{data_hex}00"


